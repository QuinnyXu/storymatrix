let lang = 'zh';
export const LANGS = ['zh', 'en'];
export const getLang = () => lang;
export const setLang = (l) => (lang = LANGS.includes(l) ? l : 'zh');
export function t(key, params = {}) {
  const v = S[key];
  let s = v ? v[lang === 'en' ? 1 : 0] : key;
  for (const [k, x] of Object.entries(params)) s = s.replaceAll(`{${k}}`, x);
  return s;
}
/** {zh, en} or a plain string -> text in the current language */
export const label = (o) => (o == null ? '' : typeof o === 'string' ? o : o[lang] || o.zh || o.en || '');
